#!/usr/bin/env python3
"""Render Compose services and profiles from parent-owned manifests."""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from validate_projects import load_manifests  # noqa: E402


def main() -> int:
    try:
        projects = load_manifests()
    except Exception as error:
        print(f"cannot generate Compose configuration: {error}", file=sys.stderr)
        return 1
    services: dict[str, dict] = {
        "gateway": {
            "build": {"context": ".", "dockerfile": "infrastructure/docker/portal.Dockerfile"},
            "ports": ["${PORTFOLIO_HTTP_PORT:-8080}:8080"],
            "volumes": ["./infrastructure/nginx/generated/compose.conf:/etc/nginx/conf.d/default.conf:ro"],
            "healthcheck": {"test": ["CMD-SHELL", "wget -q -O /dev/null http://127.0.0.1:8080/healthz || exit 1"], "interval": "15s", "timeout": "3s", "retries": 5, "start_period": "5s"},
            "restart": "unless-stopped",
        }
    }
    volumes: dict[str, dict] = {}
    for project in projects:
        backend = project["backend"]
        compose = backend.get("compose", {})
        if not compose.get("enabled"):
            continue
        if backend["kind"] == "python" and backend["framework"] == "FastAPI":
            service = compose.get("service", project["slug"])
            volumes[f"{project['slug']}-model-cache"] = {}
            services[service] = {
                "build": {"context": ".", "dockerfile": f"infrastructure/docker/{project['slug']}.Dockerfile"},
                "environment": {"HF_HOME": "/var/cache/huggingface", "PYTHONUNBUFFERED": "1"},
                "volumes": [f"{project['slug']}-model-cache:/var/cache/huggingface"],
                "profiles": [compose.get("profile", project["slug"])],
                "healthcheck": {"test": ["CMD", "python", "-c", "import urllib.request; urllib.request.urlopen('http://127.0.0.1:8000/api/health', timeout=3)"], "interval": "20s", "timeout": "5s", "retries": 10, "start_period": "180s"},
                "restart": "unless-stopped",
                "mem_limit": "2g",
            }
        elif backend["kind"] == "go":
            print(f"Skipping Compose service {project['slug']}: its manifest marks it disabled pending prerequisites.")
    config = {"services": services}
    if volumes:
        config["volumes"] = volumes
    output = "# Generated by scripts/generate_compose.py. Do not edit.\n" + json.dumps(config, indent=2) + "\n"
    (ROOT / "compose.yaml").write_text(output, encoding="utf-8", newline="\n")
    print(f"Generated compose.yaml with {len(services) - 1} optional backend service(s).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
