#!/usr/bin/env python3
"""Generate the shared Nginx gateway from enabled manifest backends."""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "infrastructure" / "nginx" / "generated"
sys.path.insert(0, str(ROOT / "scripts"))
from validate_projects import load_manifests  # noqa: E402


def routes_for(projects: list[dict], target: str) -> list[tuple[dict, dict]]:
    return [
        (project, project["backend"][target])
        for project in projects
        if project["backend"].get("kind") != "none" and project["backend"].get(target, {}).get("enabled")
    ]


def render(projects: list[dict], target: str) -> str:
    backends = routes_for(projects, target)
    lines = [
        "# Generated by scripts/generate_nginx.py. Do not edit.",
        "resolver 127.0.0.11 valid=30s ipv6=off;",
        "server {",
        "    listen 8080;",
        "    server_name _;",
        "    root /usr/share/nginx/html;",
        "    index index.html;",
        "    client_max_body_size 25m;",
        "    proxy_read_timeout 120s;",
        "    proxy_send_timeout 120s;",
        "",
        "    location ~* \\.(?:js|mjs|css|map|json|wasm|png|jpe?g|gif|webp|ico|svg|woff2?|ttf|eot)$ {",
        "        try_files $uri =404;",
        "        access_log off;",
        "        expires 7d;",
        "    }",
        "",
    ]
    for project, backend in backends:
        slug = project["slug"]
        upstream = backend.get("service", slug)
        port = backend.get("port", 8080 if backend.get("kind") == "go" else 8000)
        api_prefix = backend.get("api_prefix", "/api").rstrip("/")
        route = f"/api/{slug}/"
        lines.extend([
            f"    location ^~ {route} {{",
            f"        set $portfolio_upstream {upstream}:{port};",
            f"        rewrite ^/api/{slug}(/.*)$ {api_prefix}$1 break;",
            "        proxy_http_version 1.1;",
            "        proxy_set_header Host $host;",
            "        proxy_set_header X-Real-IP $remote_addr;",
            "        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;",
            "        proxy_set_header X-Forwarded-Proto $scheme;",
            "        proxy_set_header X-Forwarded-Host $host;",
            "        proxy_set_header Upgrade $http_upgrade;",
            "        proxy_set_header Connection \"upgrade\";",
            "        proxy_pass http://$portfolio_upstream$uri$is_args$args;",
            "    }",
            "",
        ])
    lines.extend([
        "    location ^~ /api/ {",
        "        default_type application/json;",
        "        return 404 '{\"error\":\"No backend is enabled for this API path.\"}';",
        "    }",
        "",
        "    location /search/ {",
        "        try_files $uri $uri/ /search/index.html;",
        "    }",
        "",
        "    location /work/ {",
        "        try_files $uri $uri/ /search/index.html;",
        "    }",
        "",
        "    location = /search { return 308 /search/; }",
        "",
    ])
    for project in projects:
        available_file = ROOT / "generated" / "search-index" / "built-frontends.json"
        available: set[str] = set()
        if available_file.is_file():
            try:
                available = set(json.loads(available_file.read_text(encoding="utf-8")).get("available", []))
            except (json.JSONDecodeError, OSError):
                available = set()
        if project["frontend"].get("publish") and project["slug"] in available:
            slug = project["slug"]
            lines.extend([
                f"    location = /projects/{slug} {{ return 308 /projects/{slug}/; }}",
                f"    location /projects/{slug}/ {{",
                "        try_files $uri $uri/ " + f"/projects/{slug}/index.html;",
                "    }",
                "",
            ])
    lines.extend([
        "    location = /healthz { access_log off; default_type text/plain; return 200 'ok'; }",
        "    location / { try_files $uri $uri/ /index.html; }",
        "}",
        "",
    ])
    return "\n".join(lines)


def main() -> int:
    try:
        projects = load_manifests()
    except Exception as error:
        print(f"cannot generate Nginx configuration: {error}", file=sys.stderr)
        return 1
    OUT.mkdir(parents=True, exist_ok=True)
    for target in ("compose", "render"):
        routes = routes_for(projects, target)
        (OUT / f"{target}.conf").write_text(render(projects, target), encoding="utf-8", newline="\n")
        targets = {
            project["slug"]: {"upstream_prefix": project["backend"].get("api_prefix", "/api")}
            for project, _ in routes
        }
        api_json = ROOT / "generated" / "search-index" / f"api-targets-{target}.json"
        api_json.parent.mkdir(parents=True, exist_ok=True)
        api_json.write_text(json.dumps(targets, sort_keys=True, indent=2) + "\n", encoding="utf-8")
        print(f"Generated {target} Nginx routes for {len(routes)} enabled backend(s).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
